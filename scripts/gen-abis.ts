/**
 * Generates src/lib/abis.ts from the Foundry artifacts in contracts/out.
 * Run after changing a contract: bun run scripts/gen-abis.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'

const targets = [
  { file: 'PredictionMarket', name: 'marketAbi' },
  { file: 'PriceOracleAdapter', name: 'oracleAbi' },
  { file: 'MockAggregator', name: 'aggregatorAbi' },
]

let out = '// GENERATED by scripts/gen-abis.ts from contracts/out. Do not edit by hand.\n\n'
for (const t of targets) {
  const artifact = JSON.parse(readFileSync(`contracts/out/${t.file}.sol/${t.file}.json`, 'utf8')) as { abi: unknown }
  out += `export const ${t.name} = ${JSON.stringify(artifact.abi)} as const\n\n`
}
writeFileSync('src/lib/abis.ts', out)
console.log('wrote src/lib/abis.ts')
